const (
	jpHolidayFirstYear = 2026
	jpHolidayLastYear  = 2027
)

// jpHoliday は d (JST の暦日として解釈) が祝日かを返す。covered=false は
// 表の範囲外の年 — 祝日かどうか分からない (呼び出し側で warning を出す)。
func jpHoliday(d time.Time) (name string, isHoliday, covered bool) {
	d = d.In(jst)
	if d.Year() < jpHolidayFirstYear || d.Year() > jpHolidayLastYear {
		return "", false, false
	}
	name, ok := jpHolidays[d.Format("2006-01-02")]
	return name, ok, true
}
